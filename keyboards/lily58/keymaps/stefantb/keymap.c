#define L_BASE 0
#define L_LOWER (1 << 1)
#define L_RAISE (1 << 2)
#define L_ADJUST (1 << 3)
#define L_ADJUST_TRI (L_ADJUST | L_RAISE | L_LOWER)


void render_layer(void) {
  switch (layer_state)
  {
  case L_BASE:
    oled_write_raw_P(one, sizeof(one));
    break;
  case L_RAISE:
    oled_write_raw_P(two, sizeof(two));
    break;
  case L_LOWER:
    oled_write_raw_P(three, sizeof(three));
    break;
  case L_ADJUST:
  case L_ADJUST_TRI:
    break;
  default:
break;
  }
}










